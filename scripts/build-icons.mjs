#!/usr/bin/env node
/**
 * Regenerate the brand artwork embedded in client.js.
 *
 * The client bundle is served as one browser file, so brand icons travel as
 * base64 data URIs inside it instead of extra requests. `assets/icons/*` is the
 * single source of truth: drop a replacement there and run this script.
 *
 *   node scripts/build-icons.mjs           rewrite the generated block
 *   node scripts/build-icons.mjs --check   fail when it is out of date
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = path.join(root, 'assets', 'icons');
const clientPath = path.join(root, 'client.js');
const START = '    /* brand-icons:start */';
const END = '    /* brand-icons:end */';
const MIME = {
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif'
};

function dataUriOf(file) {
  const ext = path.extname(file).toLowerCase();
  const mime = MIME[ext];
  if (!mime) throw new Error(`unsupported icon format: ${file}`);
  const bytes = readFileSync(file);
  if (mime === 'image/svg+xml') {
    const text = bytes.toString('utf8');
    if (!/<svg[\s>]/i.test(text)) throw new Error(`not an SVG document: ${file}`);
    if (!/xmlns\s*=\s*["']http:\/\/www\.w3\.org\/2000\/svg["']/i.test(text)) {
      throw new Error(`SVG is missing the xmlns attribute and cannot render standalone: ${file}`);
    }
  }
  return `data:${mime};base64,${bytes.toString('base64')}`;
}

function iconFiles() {
  return readdirSync(iconDir)
    .filter((name) => !name.startsWith('.'))
    .filter((name) => MIME[path.extname(name).toLowerCase()])
    .sort((a, b) => a.localeCompare(b));
}

function buildBlock() {
  const files = iconFiles();
  if (!files.length) throw new Error(`no icon files found in ${iconDir}`);
  const entries = files.map((name) => {
    const key = path.basename(name, path.extname(name));
    const uri = dataUriOf(path.join(iconDir, name));
    return { key, uri, size: statSync(path.join(iconDir, name)).size };
  });
  const width = Math.max(...entries.map((entry) => entry.key.length)) + 2;
  const lines = [
    '    // Generated by scripts/build-icons.mjs from assets/icons/*. Do not edit by hand.',
    '    const BRAND_ART = {',
    ...entries.map((entry) => `      ${JSON.stringify(entry.key).padEnd(width)}: '${entry.uri}',`),
    '    };'
  ];
  return { block: lines.join('\n'), entries };
}

function replaceBlock(source, block) {
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start < 0 || end < 0 || end < start) {
    throw new Error('brand icon markers not found in client.js');
  }
  const before = source.slice(0, start + START.length);
  const after = source.slice(end);
  return `${before}\n${block}\n${after}`;
}

const source = readFileSync(clientPath, 'utf8');
const { block, entries } = buildBlock();
const next = replaceBlock(source, block);
const rawBytes = entries.reduce((total, entry) => total + entry.size, 0);
const embeddedBytes = entries.reduce((total, entry) => total + entry.uri.length, 0);

if (process.argv.includes('--check')) {
  if (next !== source) {
    console.error('client.js brand artwork is out of date; run: node scripts/build-icons.mjs');
    process.exit(1);
  }
  console.log(`brand artwork up to date (${entries.length} icons, ${embeddedBytes} embedded chars)`);
} else {
  writeFileSync(clientPath, next);
  console.log(`embedded ${entries.length} brand icons: ${rawBytes} raw bytes -> ${embeddedBytes} chars`);
  for (const entry of entries) console.log(`  ${entry.key}: ${entry.size} B`);
}
